#!/usr/bin/env bash
# build/build.sh — Single-command build: produces dist/reqbot-install.sh
#
# Usage:
#   build/build.sh           # Full build → dist/reqbot-install.sh
#   build/build.sh --clean   # Remove build/linux-x86_64/ and dist/ (preserves .cache/)
#
# What this script does:
#   1. Run build/bundle.sh  — assembles build/linux-x86_64/ (Python + deps + app + models)
#   2. Write _build_info.py — bakes version + build date into the bundle
#   3. Create tarball       — tar.gz of build/linux-x86_64/
#   4. Assemble installer   — substitute version into template, append tarball
#   5. Print SHA-256        — for distribution verification
#
# Output: dist/reqbot-install.sh  (single self-extracting file, ready to distribute)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
BUNDLE_DIR="$SCRIPT_DIR/linux-x86_64"
DIST_DIR="$ROOT_DIR/dist"
INSTALLER_TEMPLATE="$SCRIPT_DIR/reqbot-install.sh"

# ---------------------------------------------------------------
# --clean: remove build artifacts (preserves .cache/ to avoid
# re-downloading the 32MB Python tarball on the next build)
# ---------------------------------------------------------------
if [ "${1-}" = "--clean" ]; then
    echo "=== ReqBot Build Clean ==="
    echo ""
    rm -rf "$BUNDLE_DIR"
    echo "[+] Removed $BUNDLE_DIR"
    rm -rf "$DIST_DIR"
    echo "[+] Removed $DIST_DIR"
    echo ""
    echo "Note: build/.cache/ (Python tarball) is preserved."
    echo "      Remove it manually if you want a fully clean slate."
    echo ""
    echo "Clean complete."
    exit 0
fi

# ---------------------------------------------------------------
# Extract version from reqbot.py using Python — avoids quote-style
# fragility (grep+cut breaks on single quotes or reformatted lines).
# ---------------------------------------------------------------
VERSION=$(python3 - "$ROOT_DIR/reqbot.py" <<'PYEOF'
import sys, ast, pathlib
src = pathlib.Path(sys.argv[1]).read_text()
tree = ast.parse(src)
for node in ast.walk(tree):
    if isinstance(node, ast.Assign):
        for t in node.targets:
            if isinstance(t, ast.Name) and t.id == "__version__":
                print(ast.literal_eval(node.value))
                sys.exit(0)
sys.exit(1)
PYEOF
)
if [ -z "$VERSION" ]; then
    echo "[-] Could not extract __version__ from reqbot.py" >&2
    exit 1
fi
BUILD_DATE=$(date -u +%Y-%m-%d)

echo "=== ReqBot Build ==="
echo ""
echo "  Version : $VERSION"
echo "  Date    : $BUILD_DATE"
echo "  Output  : $DIST_DIR/reqbot-install.sh"
echo ""

# ---------------------------------------------------------------
# Step 1: Assemble the bundle
# bundle.sh always starts clean (rm -rf linux-x86_64/) so the
# result is a reproducible build with no stale files.
# ---------------------------------------------------------------
echo "[1/4] Assembling bundle (bundle.sh)..."
bash "$SCRIPT_DIR/bundle.sh"

# ---------------------------------------------------------------
# Step 2: Write _build_info.py into app/
# reqbot.py imports this at startup to populate __version__ and
# __build_date__. Falls back to "dev" if the file is absent
# (i.e., when running from the dev tree, not a bundle).
# ---------------------------------------------------------------
echo ""
echo "[2/4] Baking version info into bundle..."
cat > "$BUNDLE_DIR/app/_build_info.py" << PYEOF
# Auto-generated by build/build.sh — do not edit.
__version__ = "$VERSION"
__build_date__ = "$BUILD_DATE"
PYEOF
echo "  _build_info.py: version=$VERSION  date=$BUILD_DATE"

# Verify reqbot --version reflects the baked version — fail if mismatch
BAKED_VERSION=$("$BUNDLE_DIR/reqbot" --version 2>&1)
echo "  Bundle reports: $BAKED_VERSION"
if ! echo "$BAKED_VERSION" | grep -qF "$VERSION"; then
    echo "[-] Version mismatch: bundle reports '$BAKED_VERSION', expected '$VERSION'" >&2
    exit 1
fi
echo "  Version check: OK"

# ---------------------------------------------------------------
# Step 3: Create tarball from build/linux-x86_64/
# Entries will be: linux-x86_64/python/... linux-x86_64/app/...
# The installer uses --strip-components=1 to extract into ~/.reqbot/
# ---------------------------------------------------------------
echo ""
echo "[3/4] Creating tarball..."
mkdir -p "$DIST_DIR"
TARBALL="$DIST_DIR/reqbot-bundle.tar.gz"
tar czf "$TARBALL" -C "$SCRIPT_DIR" linux-x86_64
echo "  Tarball: $(ls -lh "$TARBALL" | awk '{print $5}')"

# ---------------------------------------------------------------
# Step 4: Assemble the self-extracting installer
# - Substitute __REQBOT_VERSION__ placeholder in the template
# - Append the binary tarball after the __ARCHIVE_BELOW__ sentinel
# - Remove the intermediate tarball (it is now embedded)
# ---------------------------------------------------------------
echo ""
echo "[4/4] Assembling installer..."
# Verify the installer template still contains the archive sentinel.
# If someone edits reqbot-install.sh and removes __ARCHIVE_BELOW__, the
# tarball would be appended but sed extraction would silently fail at runtime.
if ! grep -q '^__ARCHIVE_BELOW__$' "$INSTALLER_TEMPLATE"; then
    echo "[-] Installer template missing __ARCHIVE_BELOW__ sentinel: $INSTALLER_TEMPLATE" >&2
    exit 1
fi
INSTALLER="$DIST_DIR/reqbot-install.sh"
sed "s/__REQBOT_VERSION__/$VERSION/g" "$INSTALLER_TEMPLATE" > "$INSTALLER"
cat "$TARBALL" >> "$INSTALLER"
chmod +x "$INSTALLER"
rm -f "$TARBALL"

INSTALLER_SIZE=$(ls -lh "$INSTALLER" | awk '{print $5}')
INSTALLER_SHA256=$(sha256sum "$INSTALLER" | cut -d' ' -f1)

# ---------------------------------------------------------------
# Summary
# ---------------------------------------------------------------
echo ""
echo "=== Build complete ==="
echo ""
echo "  Output  : $INSTALLER"
echo "  Size    : $INSTALLER_SIZE"
echo "  SHA-256 : $INSTALLER_SHA256"
echo ""
echo "To install:"
echo "  bash $INSTALLER"
echo ""
echo "To verify before installing:"
echo "  echo \"$INSTALLER_SHA256  reqbot-install.sh\" | sha256sum -c"
echo ""
